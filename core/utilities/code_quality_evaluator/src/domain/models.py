class LanguageQualityPolicy(DTO):
    """Describe complete deterministic and semantic quality rules for one language.

    Attributes:
        language: Language governed by this quality policy.
        line_length: Maximum line length, or None to disable the gate.
        documentation: Documentation requirements for the language.
        vertical_layout: Blank-line and vertical-layout requirements.
        compactness: Statement compactness and one-line restrictions.
        occurrences: Evidence collection and fixed-gate requirements.
        required_literals: Literal values required in selected artifacts.
        forbidden_literals: Literal values forbidden in selected artifacts.
        forbidden_patterns: Regular expressions forbidden in selected artifacts.
        formatters: Formatter gate specifications for the language.
        semantic_requirements: Semantic rubric requirements.
        semantic_threshold: Minimum mean semantic score for a passing result.
        semantic_policy: Model, retry, timeout, and required-layer settings.
        required_gate_ids: Gate identifiers required by this policy.
    """

    language: Language
    line_length: int | None = Field(None, ge=40, le=500)
    documentation: DocumentationPolicy
    vertical_layout: VerticalLayoutPolicy
    compactness: CompactnessPolicy
    occurrences: OccurrencePolicy
    required_literals: tuple[str, ...] = ()
    forbidden_literals: tuple[str, ...] = ()
    forbidden_patterns: tuple[str, ...] = ()
    formatters: tuple[FormatterSpec, ...] = ()
    semantic_requirements: tuple[RequirementSpec, ...] = ()
    semantic_threshold: float = Field(0.8, ge=0, le=1)
    semantic_policy: SemanticPolicy
    required_gate_ids: tuple[str, ...] = ()

    @model_validator(mode="after")
    def validate_policy(self) -> LanguageQualityPolicy:
        """Validate identifiers, references, language alignment, and categories.

        Args:
            No arguments are accepted.

        Returns:
            LanguageQualityPolicy: The validated immutable policy.

        Raises:
            ValueError: If policy collections or references are invalid.
        """

        collections = (
            self.required_literals,
            self.forbidden_literals,
            self.forbidden_patterns,
            tuple(item.id for item in self.formatters),
            tuple(item.id for item in self.semantic_requirements),
            self.required_gate_ids,
        )
        has_duplicate_values = any(
            len(set(items)) != len(items) for items in collections
        )

        if has_duplicate_values:
            raise ValueError("policy identifiers and collections must be unique")

        has_mismatched_formatter_language = any(
            item.language is not self.language for item in self.formatters
        )

        if has_mismatched_formatter_language:
            raise ValueError("formatter language must match policy language")

        has_nonsemantic_requirement = any(
            item.category is not ResultCategory.SEMANTIC
            for item in self.semantic_requirements
        )

        if has_nonsemantic_requirement:
            raise ValueError("semantic requirements must be semantic")

        return self


class EvaluatorSpec(DTO):
    """Configure deterministic and semantic evaluation for one profile.

    Attributes:
        id: Stable evaluator profile identifier.
        languages: Languages accepted by this evaluator.
        path_patterns: Logical path patterns selected at the caller boundary.
        language_policies: Exactly one quality policy per declared language.
    """

    id: str
    languages: tuple[Language, ...]
    path_patterns: tuple[str, ...] = ("**/*",)
    language_policies: tuple[LanguageQualityPolicy, ...]
    _id = field_validator("id")(_stable)

    def policy_for(self, language: Language) -> LanguageQualityPolicy:
        """Return the exact policy for a declared language.

        Args:
            language: Declared language to resolve.

        Returns:
            LanguageQualityPolicy: Matching immutable policy.

        Raises:
            ValueError: If no exact policy exists for the language.
        """

        for policy in self.language_policies:
            if policy.language is language:
                return policy

        raise ValueError("language has no quality policy")

    @model_validator(mode="after")
    def validate_profile(self) -> EvaluatorSpec:
        """Validate uniqueness and semantic-category consistency.

        Args:
            No arguments are accepted.

        Returns:
            EvaluatorSpec: Validated immutable evaluator profile.

        Raises:
            ValueError: Languages are duplicated, language policies do not exactly
                cover the evaluator languages, or a policy does not collect all
                evidence with fixed gates.
        """

        policy_languages = tuple(item.language for item in self.language_policies)
        language_count = len(self.languages)
        unique_language_count = len(set(self.languages))
        has_no_languages = language_count == 0
        has_duplicate_languages = unique_language_count != language_count

        if has_no_languages or has_duplicate_languages:
            raise ValueError("evaluator languages must be unique")

        has_duplicate_policy_languages = len(set(policy_languages)) != len(
            policy_languages
        )
        covers_exact_languages = set(policy_languages) == set(self.languages)

        if has_duplicate_policy_languages or not covers_exact_languages:
            raise ValueError("language policies must exactly cover evaluator languages")

        has_noncollecting_policy = any(
            not policy.occurrences.collect_all
            or not policy.occurrences.require_fixed_gate_set
            for policy in self.language_policies
        )

        if has_noncollecting_policy:
            raise ValueError(
                "production policies must collect all evidence with fixed gates"
            )

        return self


class CodeEvaluatorConfig(DTO):
    """Represent the complete isolated utility configuration.

    Attributes:
        default_evaluator_id: Profile selected when a request omits evaluator_id.
        evaluators: Immutable evaluator profiles.
    """

    default_evaluator_id: str
    evaluators: tuple[EvaluatorSpec, ...]
    _default_id = field_validator("default_evaluator_id")(_stable)

    @model_validator(mode="after")
    def validate_evaluators(self) -> CodeEvaluatorConfig:
        """Require unique profiles and a resolvable default profile.

        Args:
            No arguments are accepted.

        Returns:
            CodeEvaluatorConfig: Validated immutable configuration.

        Raises:
            ValueError: Profiles are empty, duplicated, or omit the default.
        """

        evaluator_ids = tuple(item.id for item in self.evaluators)

        if not evaluator_ids:
            raise ValueError("at least one evaluator is required")

        if len(set(evaluator_ids)) != len(evaluator_ids):
            raise ValueError("evaluator IDs must be unique")

        if self.default_evaluator_id not in evaluator_ids:
            raise ValueError("default evaluator is not configured")

        return self
