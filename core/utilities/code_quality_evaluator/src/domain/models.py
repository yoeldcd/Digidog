class FileEvaluationRequest(DTO):
    """Bundle source files and all deterministic evaluation inputs.

    Attributes:
        files: Immutable source artifacts to evaluate.
        requirements: Requirement declarations associated with the request.
        commands: Explicit commands to execute as deterministic gates.
        artifact_checks: Optional artifact validation gate declarations.
        formatter_checks: Optional formatter command declarations.
        evaluator_id: Optional evaluator profile override.
        baseline_paths: Relative paths identifying baseline artifacts.
        baseline_digests: Digests corresponding to baseline_paths.
    """

    files: tuple[InMemoryFile, ...]
    requirements: tuple[RequirementSpec, ...] = ()
    commands: tuple[CommandSpec, ...] = ()
    artifact_checks: tuple[ArtifactCheckSpec, ...] = ()
    formatter_checks: tuple[FormatterSpec, ...] = ()
    evaluator_id: str | None = None
    baseline_paths: tuple[str, ...] = ()
    baseline_digests: tuple[str, ...] = ()

    @field_validator("files")
    @classmethod
    def require_files(
        cls,
        files: tuple[InMemoryFile, ...],
    ) -> tuple[InMemoryFile, ...]:
        """Require at least one in-memory source artifact.

        Args:
            files: Immutable source artifacts supplied by the caller.

        Returns:
            tuple[InMemoryFile, ...]: Validated non-empty artifact tuple.

        Raises:
            ValueError: No source artifact was supplied.
        """

        if not files:
            raise ValueError("at least one file is required")

        return files

    @field_validator("baseline_paths")
    @classmethod
    def safe_paths(cls, v: tuple[str, ...]) -> tuple[str, ...]:
        """Validate every baseline path as a safe relative path.

        Args:
            v: Immutable baseline path tuple.

        Returns:
            tuple[str, ...]: Validated baseline paths.

        Raises:
            ValueError: If any baseline path is absolute, traverses a parent, or
                contains unsafe separators.
        """

        return tuple(_path(path) for path in v)

    @model_validator(mode="after")
    def validate_references(self) -> FileEvaluationRequest:
        """Validate identifier uniqueness and cross-field references.

        Args:
            No arguments are accepted.

        Returns:
            FileEvaluationRequest: This validated immutable request.

        Raises:
            ValueError: If identifiers, baseline pairs, or gate references are invalid.
        """
        collections = (
            tuple(item.path for item in self.files),
            tuple(item.id for item in self.requirements),
            tuple(item.id for item in self.commands),
            tuple(item.id for item in self.artifact_checks),
            tuple(item.id for item in self.formatter_checks),
        )
        has_duplicate_values = any(
            len(set(values)) != len(values) for values in collections
        )

        if has_duplicate_values:
            raise ValueError("duplicate request identifiers")

        has_mismatched_baselines = len(self.baseline_paths) != len(
            self.baseline_digests
        )

        if has_mismatched_baselines:
            raise ValueError("baseline paths and digests must have matching lengths")

        baseline_pairs = set(zip(self.baseline_paths, self.baseline_digests))
        has_duplicate_baseline_pairs = len(baseline_pairs) != len(self.baseline_paths)

        if has_duplicate_baseline_pairs:
            raise ValueError("baseline path and digest pairs must be unique")

        declared_ids = (
            {item.id for item in self.requirements}
            | {item.id for item in self.commands}
            | {item.id for item in self.artifact_checks}
        )
        has_unknown_gate_reference = any(
            set(item.required_gate_ids) - declared_ids for item in self.requirements
        )

        if has_unknown_gate_reference:
            raise ValueError("required gate IDs must reference declared IDs")

        return self


class Evidence(DTO):
    """Capture source evidence supporting an evaluation result.

    Attributes:
        path: Safe relative evidence path.
        line_start: Optional first relevant line.
        line_end: Optional last relevant line.
        kind: Evidence classification.
        digest: Optional SHA-256 evidence digest.
        summary: Human-readable evidence summary."""

    path: str
    line_start: int | None = Field(None, ge=1)
    line_end: int | None = Field(None, ge=1)
    kind: str
    digest: str | None = Field(None, pattern=r"^[0-9a-f]{64}$")
    summary: str = ""
    _path = field_validator("path")(_path)

    @model_validator(mode="after")
    def validate_line_range(self) -> Evidence:
        """Ensure an evidence line range is ordered when both bounds exist.

        Args:
            No arguments are accepted.

        Returns:
            Evidence: This validated immutable evidence record.

        Raises:
            ValueError: If the ending line precedes the starting line.
        """

        line_start = self.line_start
        line_end = self.line_end
        line_order_is_invalid = (
            line_start is not None and line_end is not None and line_end < line_start
        )

        if line_order_is_invalid:
            raise ValueError("line_end cannot precede line_start")

        return self


