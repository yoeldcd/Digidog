"""Immutable, strictly validated DTOs for code-quality evaluation."""

from __future__ import annotations

from enum import StrEnum

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    HttpUrl,
    field_validator,
    model_validator,
)


class EvaluationStatus(StrEnum):
    """Represent the outcome status produced by an evaluation layer.

    Members:
        PASS: The evaluation completed successfully.
        FAIL: The evaluation found one or more failing requirements.
        BLOCKED: The evaluation could not proceed because a prerequisite was unavailable.
        ERROR: The evaluation failed because of an unexpected execution error.
        DISAGREE: Evaluation layers reached conflicting outcomes.
    """

    PASS = "pass"
    FAIL = "fail"
    BLOCKED = "blocked"
    ERROR = "error"
    DISAGREE = "disagree"


class ResultCategory(StrEnum):
    """Classify a requirement by the evaluation layer that owns it.

    Members:
        DETERMINISTIC: A requirement checked by deterministic tooling.
        SEMANTIC: A requirement assessed by a semantic evaluator.
        AGGREGATE: A requirement derived from multiple evaluation layers.
    """

    DETERMINISTIC = "deterministic"
    SEMANTIC = "semantic"
    AGGREGATE = "aggregate"


class Language(StrEnum):
    """Identify source languages supported by the evaluator.

    Members:
        PYTHON: Python source code.
        JAVASCRIPT: JavaScript source code.
        TYPESCRIPT: TypeScript source code.
        MARKDOWN: Markdown documentation.
        JSON: JSON data.
        POWERSHELL: PowerShell scripts.
    """

    PYTHON = "python"
    JAVASCRIPT = "javascript"
    TYPESCRIPT = "typescript"
    MARKDOWN = "markdown"
    JSON = "json"
    POWERSHELL = "powershell"


def _stable(value: str) -> str:
    """Validate and return a stable identifier.

    Args:
        value: Candidate identifier.

    Returns:
        str: The unchanged identifier when valid.

    Raises:
        ValueError: If the identifier is empty, too long, or contains unsafe characters.
    """

    if not value:
        raise ValueError("invalid stable identifier")

    exceeds_length_limit = len(value) > 128
    normalized_value = value.replace("-", "").replace("_", "")
    contains_only_alphanumeric = normalized_value.isalnum()

    if exceeds_length_limit or not contains_only_alphanumeric:
        raise ValueError("invalid stable identifier")

    return value


def _path(value: str) -> str:
    """Validate and return a safe relative POSIX path.

    Args:
        value: Candidate relative path.

    Returns:
        str: The unchanged path when valid.

    Raises:
        ValueError: If the path is absolute, traverses parents, or contains unsafe separators.
    """

    if not value:
        raise ValueError("unsafe relative path")

    is_absolute = value.startswith(("/", "\\"))
    contains_drive_separator = ":" in value
    contains_parent_segment = ".." in value.split("/")
    contains_windows_separator = "\\" in value
    contains_duplicate_separator = "//" in value

    if (
        is_absolute
        or contains_drive_separator
        or contains_parent_segment
        or contains_windows_separator
        or contains_duplicate_separator
    ):
        raise ValueError("unsafe relative path")

    return value


def _model_name(value: str) -> str:
    """Validate and return a provider model identifier.

    Args:
        value: Candidate model name.

    Returns:
        str: The unchanged model name when valid.

    Raises:
        ValueError: If the name is empty, too long, or contains unsupported characters.
    """

    if not value:
        raise ValueError("invalid model identifier")

    allowed_punctuation = {"-", "_", ".", "/", ":"}
    has_invalid_character = any(
        not character.isalnum() and character not in allowed_punctuation
        for character in value
    )
    exceeds_length_limit = len(value) > 256
    starts_with_alphanumeric = value[0].isalnum()

    if exceeds_length_limit or not starts_with_alphanumeric or has_invalid_character:
        raise ValueError("invalid model identifier")

    return value


class DTO(BaseModel):
    """Provide immutable, strict, extra-forbidden behavior for all DTOs."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    @classmethod
    def json_schema(cls) -> dict[str, object]:
        """Return the generated JSON schema for this DTO class.

        Args:
            No arguments are accepted.

        Returns:
            dict[str, object]: JSON-schema mapping generated by Pydantic.
        """

        return cls.model_json_schema()


class ModelSpec(DTO):
    """Describe one unresolved model provider configuration.

    Attributes:
        model: Provider model identifier.
        base_url: HTTPS provider endpoint.
        api_key: Environment-variable credential reference.
        temperature: Sampling temperature.
        max_tokens: Maximum generated token count.
        enabled: Whether this model may run."""

    model: str
    base_url: HttpUrl
    api_key: str = Field(pattern=r"^\$[A-Za-z_][A-Za-z0-9_]*$")
    temperature: float = Field(0.0, ge=0, le=2)
    max_tokens: int = Field(2048, gt=0, le=1000000)
    enabled: bool = True

    @field_validator("model")
    @classmethod
    def valid_model(cls, value: str) -> str:
        """Validate the configured model identifier.

        Args:
            value: Candidate provider model identifier.

        Returns:
            str: The unchanged identifier when it satisfies the provider syntax.

        Raises:
            ValueError: If the identifier is empty, too long, or contains unsupported characters.
        """

        return _model_name(value)

    @field_validator("base_url")
    @classmethod
    def require_https(cls, value: HttpUrl) -> HttpUrl:
        """Require model provider URLs to use HTTPS.

        Args:
            value: Parsed provider endpoint.

        Returns:
            HttpUrl: The unchanged HTTPS endpoint.

        Raises:
            ValueError: If the endpoint uses a non-HTTPS scheme.
        """

        if value.scheme != "https":
            raise ValueError("base_url must use HTTPS")

        return value


