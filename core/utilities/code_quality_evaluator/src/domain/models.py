class CommandSpec(DTO):
    """Describe one executable command and execution limits.

    Attributes:
        id: Stable command identifier.
        argv: Immutable executable argument vector.
        expected_exit_code: Successful process exit code.
        timeout: Maximum execution duration in seconds.
        retry: Retry policy for failed executions."""

    id: str
    argv: tuple[str, ...]
    expected_exit_code: int = 0
    timeout: float = Field(60, gt=0, le=86400)
    retry: RetrySpec = RetrySpec()
    _id = field_validator("id")(_stable)

    @field_validator("argv")
    @classmethod
    def valid_argv(cls, v: tuple[str, ...]) -> tuple[str, ...]:
        """Require a non-empty argument vector without NUL bytes.

        Args:
            v: Immutable command argument vector.

        Returns:
            tuple[str, ...]: The validated argument vector.

        Raises:
            ValueError: If no arguments are supplied or an argument contains NUL.
        """

        if not v:
            raise ValueError("argv must be non-empty")

        has_invalid_argument = any(not argument or "\x00" in argument for argument in v)

        if has_invalid_argument:
            raise ValueError("argv must be non-empty")

        return v


